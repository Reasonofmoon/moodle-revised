$configfile = $rootdir . '/academy_config.json';
$resetleadsflag = false;
foreach ($argv ?? [] as $arg) {
    if (strpos($arg, '--config=') === 0) {
        $configfile = substr($arg, 9);
    } else if ($arg === '--reset-leads') {
        $resetleadsflag = true;
    } else if ($arg === '--help' || $arg === '-h') {
        echo "Usage: php provision_academy.php [--config=/path/to/academy_config.json] [--reset-leads]\n";
        exit(0);
    }
}

if (!file_exists($configfile)) {
    fwrite(STDERR, "Config file not found: {$configfile}\n");
    exit(1);
}

$cfg = json_decode(file_get_contents($configfile), true);
if (!is_array($cfg) || empty($cfg['academy'])) {
    fwrite(STDERR, "Invalid JSON in {$configfile}\n");
    exit(1);
}

// ---------------------------------------------------------------------------
// Step 0-A: Ensure Composer vendor/autoload.php is installed (for fresh git clone)
// ---------------------------------------------------------------------------
if (!file_exists($rootdir . '/vendor/autoload.php') && file_exists($rootdir . '/composer.json')) {
    echo "[Step 0] vendor/autoload.php 미존재 감지 -> Composer 의존성 자동 설치 중...\n";
    passthru('cd ' . escapeshellarg($rootdir) . ' && composer install --no-dev --optimize-autoloader --no-interaction', $compret);
    if ($compret !== 0) {
        fwrite(STDERR, "Composer 설치 실패 (코드: {$compret})\n");
        exit($compret);
