// ---------------------------------------------------------------------------
// Step 0-B: Auto-generate config.php if missing
// ---------------------------------------------------------------------------
if (!file_exists($configphp)) {
    $dbhost = getenv('MOODLE_DB_HOST') ?: 'db';
    $dbname = getenv('MOODLE_DB_NAME') ?: 'moodle';
    $dbuser = getenv('MOODLE_DB_USER') ?: 'moodleuser';
    $dbpass = getenv('MOODLE_DB_PASS') ?: 'readmaster_db_pass';
    $wwwroot = getenv('MOODLE_WWWROOT') ?: 'http://localhost:8080';
    $dataroot = getenv('MOODLE_DATAROOT') ?: '/var/www/moodledata';

    $configcontent = <<<PHP
<?php  // Moodle configuration file (Auto-generated by provision_academy.php)

unset(\$CFG);
global \$CFG;
\$CFG = new stdClass();

\$CFG->dbtype    = 'mariadb';
\$CFG->dblibrary = 'native';
\$CFG->dbhost    = '{$dbhost}';
\$CFG->dbname    = '{$dbname}';
\$CFG->dbuser    = '{$dbuser}';
\$CFG->dbpass    = '{$dbpass}';
\$CFG->prefix    = 'mdl_';
\$CFG->dboptions = array (
  'dbpersist' => 0,
  'dbport' => '',
  'dbsocket' => '',
  'dbcollation' => 'utf8mb4_unicode_ci',
);

\$CFG->wwwroot   = '{$wwwroot}';
\$CFG->dataroot  = '{$dataroot}';
\$CFG->admin     = 'admin';

\$CFG->directorypermissions = 02777;
\$CFG->routerconfigured = true;

require_once(__DIR__ . '/lib/setup.php');
PHP;
    file_put_contents($configphp, $configcontent);
    echo "[Step 0] config.php 자동 생성 완료 ({$wwwroot})\n";
}

// ---------------------------------------------------------------------------
// Step 0-B: Check if MariaDB has Moodle core tables (mdl_config). If empty, install!
// ---------------------------------------------------------------------------
$rawconfig = file_get_contents($configphp);
preg_match("/\\\$CFG->dbhost\s*=\s*'([^']+)'/", $rawconfig, $mhost);
preg_match("/\\\$CFG->dbname\s*=\s*'([^']+)'/", $rawconfig, $mname);
preg_match("/\\\$CFG->dbuser\s*=\s*'([^']+)'/", $rawconfig, $muser);
preg_match("/\\\$CFG->dbpass\s*=\s*'([^']+)'/", $rawconfig, $mpass);
$dbhost = $mhost[1] ?? 'db';
$dbname = $mname[1] ?? 'moodle';
$dbuser = $muser[1] ?? 'moodleuser';
$dbpass = $mpass[1] ?? 'readmaster_db_pass';

$maxretries = 30;
$mysqli = null;
for ($i = 1; $i <= $maxretries; $i++) {
    try {
        $mysqli = @new mysqli($dbhost, $dbuser, $dbpass, $dbname);
        if (!$mysqli->connect_errno) {
            break;
        }
    } catch (\Throwable $e) {
        // Wait for MariaDB container readiness
    }
    echo "[DB 대기중] MariaDB({$dbhost}) 연결 대기 중... ({$i}/{$maxretries})\n";
    sleep(2);
}

if (!$mysqli || $mysqli->connect_errno) {
    fwrite(STDERR, "MariaDB 연결 실패: " . ($mysqli ? $mysqli->connect_error : 'timeout') . "\n");
    exit(1);
}

$tablecheck = $mysqli->query("SHOW TABLES LIKE 'mdl_config'");
$hascoretables = ($tablecheck && $tablecheck->num_rows > 0);
$mysqli->close();

if (!$hascoretables) {
    echo "=================================================================\n";
    echo "[최초 설치 감지] 빈 데이터베이스가 감지되었습니다.\n";
    echo "무들 코어 DB 테이블 및 초기 커리큘럼 자동 설치를 시작합니다...\n";
    echo "=================================================================\n";

    $adminuser = escapeshellarg($cfg['accounts']['admin_user'] ?? 'readmaster');
    $adminpass = escapeshellarg($cfg['accounts']['admin_pass'] ?? 'darlbit123');
    $adminemail = escapeshellarg($cfg['academy']['support_email'] ?? 'support@academy.kr');
    $fn = escapeshellarg($cfg['academy']['fullname'] ?? '리드마스터 영어독해·원서리딩 학원');
    $sn = escapeshellarg($cfg['academy']['shortname'] ?? '리드마스터 학원');

    $installcmd = sprintf(
        'php %s/admin/cli/install_database.php --lang=ko --adminuser=%s --adminpass=%s --adminemail=%s --fullname=%s --shortname=%s --agree-license',
        escapeshellarg($rootdir),
        $adminuser,
        $adminpass,
        $adminemail,
        $fn,
        $sn
    );
    passthru($installcmd, $ret);
    if ($ret !== 0) {
        fwrite(STDERR, "install_database.php 실행 실패 (코드: {$ret})\n");
        exit($ret);
    }

    if (file_exists($rootdir . '/setup_readmaster.php')) {
        echo "[초기 커리큘럼 시딩] setup_readmaster.php 실행 중...\n";
        passthru('php ' . escapeshellarg($rootdir . '/setup_readmaster.php'));
    }
}

